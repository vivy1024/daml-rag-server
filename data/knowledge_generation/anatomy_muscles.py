def generate_anatomy_muscles() -> List[Dict]:
    """生成肌肉解剖学知识 chunks"""
    chunks = []

    for muscle in MUSCLE_DATA:
        # 获取图谱对应的肌群名称
        graph_muscles = ANATOMY_TO_GRAPH.get(muscle["name"], [muscle["name"]])

        # Chunk 1: 基础解剖（起止点+功能）
        content = (
            f"## {muscle['name']}的解剖学\n\n"
            f"**起点**：{muscle['origin']}\n\n"
            f"**止点**：{muscle['insertion']}\n\n"
            f"**功能**：{muscle['function']}\n\n"
            f"**神经支配**：{muscle['nerve']}\n\n"
            f"**肌纤维类型**：{muscle['fiber_type']}"
        )
        chunks.append(make_chunk(
            category="anatomy",
            subcategory="muscle_anatomy",
            title=f"{muscle['name']} — 起止点与功能",
            content=content,
            keywords=[muscle["name"]] + graph_muscles + ["起止点", "功能", "解剖"],
            related_muscles=graph_muscles,
        ))

        # Chunk 2: 训练关系
        content = (
            f"## {muscle['name']}的训练\n\n"
            f"**推荐训练动作**：{muscle['training']}\n\n"
            f"**协同肌**：{muscle['synergist']}\n\n"
            f"**拮抗肌**：{muscle['antagonist']}\n\n"
            f"**常见问题**：{muscle['common_issues']}"
        )
        chunks.append(make_chunk(
            category="anatomy",
            subcategory="muscle_training",
            title=f"{muscle['name']} — 训练与常见问题",
            content=content,
            keywords=[muscle["name"]] + graph_muscles + ["训练", "协同肌", "拮抗肌"],
            related_muscles=graph_muscles,
        ))

    return chunks



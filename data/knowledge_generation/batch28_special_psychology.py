def generate_batch28() -> List[Dict]:
    chunks = []
    for item in SPECIAL_DATA:
        muscles = normalize_muscles(item.get("muscles", []))
        cat = "special_populations" if "患者" in item["title"] or "青少年" in item["title"] else "psychology"
        chunks.append(make_chunk(
            category=cat,
            subcategory="guidelines" if cat == "special_populations" else "mental_skills",
            title=item["title"],
            content=item["content"],
            keywords=item["keywords"],
            related_muscles=muscles,
        ))
    return chunks



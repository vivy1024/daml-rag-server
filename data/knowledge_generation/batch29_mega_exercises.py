            name=ex["name"],
            target=ex["target"],
            secondary=ex["secondary"],
            steps=ex["steps"],
            breathing=ex["breathing"],
            errors="\n".join(f"- {e}" for e in ex["errors"].split("|")),
            tips=ex["tips"],

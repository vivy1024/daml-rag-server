def normalize_muscles(muscle_list: list) -> list:
    """将肌肉名称列表标准化为图谱节点名称"""
    result = []
    for m in muscle_list:
        normalized = MUSCLE_ALIAS_MAP.get(m, m)
        if normalized in GRAPH_MUSCLES and normalized not in result:
            result.append(normalized)
    return result

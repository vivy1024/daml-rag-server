def generate_batch50() -> List[Dict]:
    chunks = []
    for item in DATA:
        muscles = normalize_muscles(item.get("muscles", []))
        chunks.append(make_chunk(
            category=item.get("cat", "methodology"),
            subcategory=item.get("sub", "training"),
            title=item["title"],
            content=item["content"],
            keywords=item["keywords"],
            related_muscles=muscles,
        ))
    return chunks

if __name__ == "__main__":
    chunks = generate_batch50()
    print(f"生成 {len(chunks)} chunks")
    output_dir = os.path.join(os.path.dirname(__file__), "output")
    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, "batch50.json"), "w", encoding="utf-8") as f:
        json.dump(chunks, f, ensure_ascii=False, indent=2)
    print("已保存到 output/batch50.json")

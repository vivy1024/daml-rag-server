def generate_batch21() -> List[Dict]:
    """生成 batch21 动作教学 chunks"""
    chunks = []
    for item in MOVEMENT_DATA:
        muscles = normalize_muscles(item.get("muscles", []))
        chunks.append(make_chunk(
            category="methodology",
            subcategory="exercise_technique",
            title=item["title"],
            content=item["content"],
            keywords=item["keywords"],
            related_muscles=muscles,
        ))
    return chunks


if __name__ == "__main__":
    chunks = generate_batch21()
    print(f"生成 {len(chunks)} 个动作教学 chunks")
    output_dir = os.path.join(os.path.dirname(__file__), "output")
    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, "batch21.json"), "w", encoding="utf-8") as f:
        json.dump(chunks, f, ensure_ascii=False, indent=2)
    print("已保存到 output/batch21.json")

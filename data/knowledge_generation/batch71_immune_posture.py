    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, "batch71.json"), "w", encoding="utf-8") as f:
        json.dump(chunks, f, ensure_ascii=False, indent=2)
    print("已保存到 output/batch71.json")

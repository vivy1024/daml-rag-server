def generate_rehabilitation() -> List[Dict]:
    """生成康复训练知识 chunks"""
    chunks = []

    for rehab in REHAB_DATA:
        # Chunk 1: 损伤机制与分级
        content = (
            f"## {rehab['injury']} — 损伤机制与分级\n\n"
            f"**损伤机制**：{rehab['mechanism']}\n\n"
            f"**分级**：{rehab['grading']}\n\n"
            f"**红旗信号（需立即就医）**：{rehab['red_flags']}"
        )
        chunks.append(make_chunk(
            category="rehabilitation",
            subcategory="injury_mechanism",
            title=f"{rehab['injury']} — 损伤机制与分级",
            content=content,
            keywords=[rehab["injury"], "损伤机制", "分级", "红旗信号"],
            related_injuries=[rehab["graph_name"]],
        ))

        # Chunk 2-N: 每个康复阶段一个 chunk
        for phase in rehab["phases"]:
            content = (
                f"## {rehab['injury']} — {phase['name']}\n\n"
                f"**目标**：{phase['goal']}\n\n"
                f"**推荐训练**：{phase['exercises']}\n\n"
                f"**禁忌/避免**：{phase['avoid']}"
            )
            chunks.append(make_chunk(
                category="rehabilitation",
                subcategory="rehab_protocol",
                title=f"{rehab['injury']} — {phase['name']}",
                content=content,
                keywords=[rehab["injury"], phase["name"].split("（")[0], "康复", "训练"],
                related_injuries=[rehab["graph_name"]],
            ))

        # Chunk 最后: 重返训练标准
        content = (
            f"## {rehab['injury']} — 重返训练标准\n\n"
            f"**重返标准**：{rehab['return_criteria']}\n\n"
            f"**红旗信号**：{rehab['red_flags']}"
        )
        chunks.append(make_chunk(
            category="rehabilitation",
            subcategory="return_criteria",
            title=f"{rehab['injury']} — 重返训练标准",
            content=content,
            keywords=[rehab["injury"], "重返训练", "标准", "评估"],
            related_injuries=[rehab["graph_name"]],
        ))

    return chunks

